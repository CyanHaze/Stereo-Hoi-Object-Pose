#!/usr/bin/env python
"""
Multi-view pose fusion: combines left and right FoundationPose tracking results
into a single pose sequence in the left-camera coordinate frame.

PREREQUISITE — these must already exist on disk (generated by run_fp_track.py):
    foundationpose_v2/run/ob_in_cam/*.txt       (from: run_fp_track.py --camera left)
    foundationpose_v2/run_right/ob_in_cam/*.txt (from: run_fp_track.py --camera right)

This script does NOT run FoundationPose — it only reads the pose files above and fuses them.

Input:
    foundationpose_v2/run/ob_in_cam/*.txt         (left-camera poses)
    foundationpose_v2/run_right/ob_in_cam/*.txt   (right-camera poses)
    calib.json                                    (baseline_m)
    ffs/cam_K.txt                                 (intrinsics, for --vis only)

Output:
    foundationpose_v2/fused/ob_in_cam/*.txt       (fused poses, left-cam frame)
    foundationpose_v2/fused/track_vis/*.png       (--vis: mesh render + box + axis)
    foundationpose_v2/fused/video_frames/*.png    (--vis: RGB overlay + box + axis)

Usage:
    # Fusion only (no GPU needed)
    python scripts/run_fusion.py --clip clip03

    # Fusion + visualization (needs FoundationPose Docker container)
    python scripts/run_fusion.py --clip clip03 --vis

    # With outlier rejection + Gaussian temporal smoothing (recommended)
    python scripts/run_fusion.py --clip clip03 --method average --smooth 7 --vis

    # Tighter outlier thresholds (reject right frame if L-R diff > 3cm or > 15deg)
    python scripts/run_fusion.py --clip clip03 --outlier_trans 0.03 --outlier_rot 15

    # Ablation: left-only baseline
    python scripts/run_fusion.py --clip clip03 --method left_only --vis

    # Disable outlier rejection (use all right frames)
    python scripts/run_fusion.py --clip clip03 --no_outlier --vis
"""

import argparse, os, sys, json, glob, logging

code_dir = os.path.dirname(os.path.realpath(__file__))
repo_dir = os.path.dirname(code_dir)

import numpy as np
import cv2


# ---------------------------------------------------------------------------
# Pure-numpy rotation (replaces scipy.spatial.transform.Rotation)
# ---------------------------------------------------------------------------

class Rotation:
    """Minimal pure-numpy Rotation class (drop-in for scipy.spatial.transform.Rotation)."""

    def __init__(self, quat):
        self._q = np.asarray(quat, dtype=np.float64)

    @classmethod
    def from_matrix(cls, mat):
        """3x3 rotation matrix -> Rotation."""
        m = np.asarray(mat, dtype=np.float64)
        trace = np.trace(m)
        if trace > 0:
            s = np.sqrt(trace + 1.0) * 2.0
            w = 0.25 * s
            x = (m[2, 1] - m[1, 2]) / s
            y = (m[0, 2] - m[2, 0]) / s
            z = (m[1, 0] - m[0, 1]) / s
        elif m[0, 0] > m[1, 1] and m[0, 0] > m[2, 2]:
            s = np.sqrt(1.0 + m[0, 0] - m[1, 1] - m[2, 2]) * 2.0
            w = (m[2, 1] - m[1, 2]) / s
            x = 0.25 * s
            y = (m[0, 1] + m[1, 0]) / s
            z = (m[0, 2] + m[2, 0]) / s
        elif m[1, 1] > m[2, 2]:
            s = np.sqrt(1.0 + m[1, 1] - m[0, 0] - m[2, 2]) * 2.0
            w = (m[0, 2] - m[2, 0]) / s
            x = (m[0, 1] + m[1, 0]) / s
            y = 0.25 * s
            z = (m[1, 2] + m[2, 1]) / s
        else:
            s = np.sqrt(1.0 + m[2, 2] - m[0, 0] - m[1, 1]) * 2.0
            w = (m[1, 0] - m[0, 1]) / s
            x = (m[0, 2] + m[2, 0]) / s
            y = (m[1, 2] + m[2, 1]) / s
            z = 0.25 * s
        return cls([x, y, z, w])

    @classmethod
    def from_quat(cls, q):
        """Quaternion [x,y,z,w] -> Rotation."""
        return cls(q)

    def as_quat(self):
        """Return [x, y, z, w]."""
        return self._q.copy()

    def as_matrix(self):
        """Return 3x3 rotation matrix."""
        x, y, z, w = self._q
        return np.array([
            [1 - 2*y*y - 2*z*z,     2*x*y - 2*z*w,     2*x*z + 2*y*w],
            [    2*x*y + 2*z*w, 1 - 2*x*x - 2*z*z,     2*y*z - 2*x*w],
            [    2*x*z - 2*y*w,     2*y*z + 2*x*w, 1 - 2*x*x - 2*y*y],
        ], dtype=np.float64)


R = Rotation  # alias, same interface as scipy

# ---------------------------------------------------------------------------
# Coordinate transform
# ---------------------------------------------------------------------------

def build_left_from_right(baseline_m):
    """Right camera -> left camera transform for rectified stereo.

    In rectified stereo the right camera is at [baseline, 0, 0] in the
    left-camera frame.  Hence T_left_from_right = translate(+baseline, 0, 0).
    """
    T = np.eye(4)
    T[0, 3] = baseline_m
    return T


