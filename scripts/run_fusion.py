def load_poses(txt_dir, id_strs):
    """Load 4x4 pose matrices from a directory of .txt files.

    Returns (poses, missing_ids).
    """
    N = len(id_strs)
    poses = np.zeros((N, 4, 4), dtype=np.float64)
    missing = np.zeros(N, dtype=bool)
    for i, sid in enumerate(id_strs):
        path = os.path.join(txt_dir, f'{sid}.txt')
        if os.path.exists(path):
            poses[i] = np.loadtxt(path).reshape(4, 4)
        else:
            missing[i] = True
    return poses, missing


def save_poses(txt_dir, id_strs, poses):
    """Save 4x4 poses as .txt files."""
    os.makedirs(txt_dir, exist_ok=True)
    for i, sid in enumerate(id_strs):
        np.savetxt(os.path.join(txt_dir, f'{sid}.txt'), poses[i].reshape(4, 4))


# ---------------------------------------------------------------------------
# Pose fusion
# ---------------------------------------------------------------------------

def _copy_available(poses_left_i, poses_right_i):
    """Return whichever of left/right has a non-zero pose."""
    if not np.all(poses_left_i == 0):
        return poses_left_i.copy()
    return poses_right_i.copy()


def _rotation_diff_deg(R_l, R_r):
    """Angular distance between two 3x3 rotation matrices, in degrees."""
    dR = R_l.T @ R_r
    cos = (np.trace(dR) - 1.0) / 2.0
    cos = np.clip(cos, -1.0, 1.0)
    return float(np.degrees(np.arccos(cos)))


def _mean_rotation(r_l, r_r):
    """Quaternion average with sign-disambiguation."""
    q_l = r_l.as_quat()
    q_r = r_r.as_quat()
    if np.dot(q_l, q_r) < 0:
        q_r = -q_r
    q = q_l + q_r
    q /= np.linalg.norm(q)
    return R.from_quat(q)


def fuse_average(poses_left, poses_right, valid):
    """Equal-weight fusion: quaternion-mean rotation, arithmetic-mean translation."""
    N = len(valid)
    fused = np.zeros((N, 4, 4), dtype=np.float64)
    for i in range(N):
        if not valid[i]:
            fused[i] = _copy_available(poses_left[i], poses_right[i])
            continue

        r_l = R.from_matrix(poses_left[i, :3, :3])
        r_r = R.from_matrix(poses_right[i, :3, :3])
        r_fused = _mean_rotation(r_l, r_r)
        t_fused = (poses_left[i, :3, 3] + poses_right[i, :3, 3]) / 2.0

        fused[i, :3, :3] = r_fused.as_matrix()
        fused[i, :3, 3] = t_fused
        fused[i, 3, 3] = 1.0
    return fused


def fuse_left_main(poses_left, poses_right, valid,
                   trans_thresh=0.02, rot_thresh_deg=10.0):
    """Left-main fusion: use left by default, average only when left and right agree.

    If translation diff < trans_thresh (m) AND rotation diff < rot_thresh_deg,
    fall through to average.  Otherwise keep left unchanged.
    """
    N = len(valid)
    fused = np.zeros((N, 4, 4), dtype=np.float64)
    n_avg, n_left = 0, 0
    for i in range(N):
        if not valid[i]:
            fused[i] = _copy_available(poses_left[i], poses_right[i])
            continue

        t_l = poses_left[i, :3, 3]
        t_r = poses_right[i, :3, 3]
        trans_diff = float(np.linalg.norm(t_l - t_r))
        rot_diff = _rotation_diff_deg(poses_left[i, :3, :3], poses_right[i, :3, :3])

        if trans_diff < trans_thresh and rot_diff < rot_thresh_deg:
            r_l = R.from_matrix(poses_left[i, :3, :3])
            r_r = R.from_matrix(poses_right[i, :3, :3])
            r_fused = _mean_rotation(r_l, r_r)
            t_fused = (t_l + t_r) / 2.0
            fused[i, :3, :3] = r_fused.as_matrix()
            fused[i, :3, 3] = t_fused
            n_avg += 1
        else:
            fused[i] = poses_left[i].copy()
            n_left += 1

        fused[i, 3, 3] = 1.0

    logging.info(f"  left_main: {n_avg} averaged, {n_left} left-only "
                 f"(thresholds: trans<{trans_thresh:.3f}m, rot<{rot_thresh_deg:.0f}deg)")
    return fused


# ---------------------------------------------------------------------------
# Outlier detection
# ---------------------------------------------------------------------------

def detect_outliers(poses_left, poses_right, valid,
                    trans_thresh=0.05, rot_thresh_deg=30.0):
    """Mark frames where right tracking likely failed as invalid.

    A frame is an outlier if left-right translation diff > trans_thresh (m)
    OR left-right rotation diff > rot_thresh_deg.

    Returns (valid_out, n_outliers).
    """
    valid_out = valid.copy()
    n_outliers = 0
    diffs = []
    for i in range(len(valid)):
        if not valid[i]:
            continue
        t_diff = float(np.linalg.norm(poses_left[i, :3, 3] - poses_right[i, :3, 3]))
        r_diff = _rotation_diff_deg(poses_left[i, :3, :3], poses_right[i, :3, :3])
        diffs.append((t_diff, r_diff))
        if t_diff > trans_thresh or r_diff > rot_thresh_deg:
            valid_out[i] = False
            n_outliers += 1

    diffs = np.array(diffs) if diffs else np.zeros((0, 2))
    if len(diffs) > 0:
        logging.info(f"  Outlier check: {n_outliers}/{len(diffs)} frames rejected "
                     f"(trans>{trans_thresh*1000:.0f}mm | rot>{rot_thresh_deg:.0f}deg)")
        logging.info(f"  L-R stats (valid frames): "
                     f"trans median={np.median(diffs[:,0])*1000:.1f}mm "
                     f"max={diffs[:,0].max()*1000:.1f}mm | "
                     f"rot median={np.median(diffs[:,1]):.1f}deg "
                     f"max={diffs[:,1].max():.1f}deg")
    return valid_out


# ---------------------------------------------------------------------------
# Temporal smoothing
# ---------------------------------------------------------------------------

def _gaussian_kernel(size, sigma=None):
    """1D Gaussian kernel."""
    if sigma is None:
        sigma = size / 4.0
    x = np.arange(size) - (size - 1) / 2.0
    k = np.exp(-0.5 * (x / sigma) ** 2)
    return k / k.sum()


def smooth_poses(poses, window=5, method='gaussian'):
    """Smooth a pose sequence in quaternion + translation space.

    Args:
        window: kernel size (odd)
        method: 'moving_avg' (uniform) or 'gaussian' (Gaussian-weighted, default)
    """
    if window <= 1:
        return poses.copy()

    if window % 2 == 0:
        window += 1

    N = poses.shape[0]
    quats = np.zeros((N, 4))
    trans = np.zeros((N, 3))
    for i in range(N):
        quats[i] = R.from_matrix(poses[i, :3, :3]).as_quat()
        trans[i] = poses[i, :3, 3]

    for i in range(1, N):
        if np.dot(quats[i], quats[i - 1]) < 0:
            quats[i] = -quats[i]

    if method == 'gaussian':
        kernel = _gaussian_kernel(window)
    else:
        kernel = np.ones(window) / window

    half = window // 2
    smoothed_quat = np.zeros_like(quats)
    smoothed_trans = np.zeros_like(trans)

    for i in range(N):
        lo = max(0, i - half)
        hi = min(N, i + half + 1)
        k_lo = half - (i - lo)
        k_hi = half + (hi - i)
        k = kernel[k_lo:k_hi]
        k = k / k.sum()
        smoothed_quat[i] = (quats[lo:hi].T @ k).T
        smoothed_trans[i] = (trans[lo:hi].T @ k).T

    norms = np.linalg.norm(smoothed_quat, axis=1, keepdims=True)
    smoothed_quat /= norms

    smoothed = poses.copy()
    for i in range(N):
        smoothed[i, :3, :3] = R.from_quat(smoothed_quat[i]).as_matrix()
        smoothed[i, :3, 3] = smoothed_trans[i]
    return smoothed


